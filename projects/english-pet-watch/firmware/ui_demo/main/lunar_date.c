bool lunar_date_format(int year, int month, int day, char *out, size_t size)
{
    if (out == NULL || size == 0) return false;
    out[0] = 0;
    /* shortcut: 离线表覆盖 2024–2050；需要显示更远日期时扩展天文台月初索引。 */
    if (year < 2024 || year > 2050 || month < 1 || month > 12 || day < 1) return false;
    static const int days[] = {31,28,31,30,31,30,31,31,30,31,30,31};
    bool leap = year % 4 == 0;
    if (day > days[month - 1] + (month == 2 && leap)) return false;
    int offset = day - 1;
    for (int y = 2023; y < year; y++) offset += 365 + (y % 4 == 0);
    for (int m = 1; m < month; m++) offset += days[m - 1] + (m == 2 && leap);
    unsigned index = 0;
    while (index + 1 < sizeof(lunar_months) / sizeof(lunar_months[0]) &&
           lunar_months[index + 1].start <= offset) index++;
    unsigned lm = lunar_months[index].month;
    unsigned ld = offset - lunar_months[index].start + 1;
    if (ld < 1 || ld > 30) return false;
    static const char *months[] = {"正月","二月","三月","四月","五月","六月",
                                    "七月","八月","九月","十月","冬月","腊月"};
    static const char *digits[] = {"一","二","三","四","五","六","七","八","九","十"};
    const char *prefix = ld <= 10 ? "初" : ld == 20 ? "二" : ld < 20 ? "十" : ld < 30 ? "廿" : "三";
    const char *suffix = ld == 20 || ld == 30 ? "十" : digits[(ld - 1) % 10];
    int written = snprintf(out, size, "农历 %s%s%s%s", lm & 16 ? "闰" : "", months[(lm & 15) - 1], prefix, suffix);
    if (written < 0 || (size_t)written >= size) {out[0] = 0; return false;}
    return true;
}
